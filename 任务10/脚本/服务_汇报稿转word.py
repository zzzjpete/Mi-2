def add(doc, text, size, bold):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    return p


doc = Document()
sec = doc.sections[0]
add(doc, TITLE, 16, True)
for head, paras in BLOCKS:
    add(doc, head, 12, True)
    for t in paras:
        add(doc, t, 10.5, False)

doc.save(OUT)

